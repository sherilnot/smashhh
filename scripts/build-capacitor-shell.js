#!/usr/bin/env node
/**
 * Prepare the local web assets that ship inside the iOS binary.
 *
 * Two things need to be generated rather than committed:
 *
 *   1. assets/logo.png — copied from public/images so the bundled launch and
 *      offline screens stay in sync with the web app's branding.
 *   2. assets/config.js — exposes the deployed app URL to the offline page.
 *      The native bridge's window.Capacitor.getServerUrl() returns the *local*
 *      scheme (capacitor://localhost), not the remote server, so the offline
 *      page's retry button has no other way to learn where to reconnect to.
 *
 * Run automatically by `npm run cap:sync`.
 */

const fs = require('fs');
const path = require('path');

const { resolveAppUrl } = require('../capacitor/app-url');

const ROOT = path.join(__dirname, '..');
const SHELL_DIR = path.join(ROOT, 'capacitor', 'shell');
const ASSETS_DIR = path.join(SHELL_DIR, 'assets');
const LOGO_SOURCE = path.join(ROOT, 'public', 'images', 'logo.png');

function main() {
  // Fail fast and loudly: a build with no URL produces an app that opens to a
  // permanent loading screen.
  const appUrl = resolveAppUrl({ required: true });

  fs.mkdirSync(ASSETS_DIR, { recursive: true });

  if (!fs.existsSync(LOGO_SOURCE)) {
    throw new Error(`Expected the web app logo at ${LOGO_SOURCE} but it is missing.`);
  }
  fs.copyFileSync(LOGO_SOURCE, path.join(ASSETS_DIR, 'logo.png'));

  // JSON.stringify keeps the value safely escaped inside the JS literal.
  const configJs =
    '// Generated by scripts/build-capacitor-shell.js — do not edit.\n' +
    `window.__APP_URL__ = ${JSON.stringify(appUrl)};\n`;
  fs.writeFileSync(path.join(ASSETS_DIR, 'config.js'), configJs, 'utf8');

  console.log(`[capacitor] shell assets built for ${appUrl}`);
}

try {
  main();
} catch (error) {
  console.error(`[capacitor] ${error.message}`);
  process.exit(1);
}
